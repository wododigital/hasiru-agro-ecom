// Plan 9.13 (pipeline half): docs/CLIENT-QUESTIONS.md generated from the seed's needs_review records and
// research section 11. The admin "Data gaps" view (catalog) reads the same flags from the database.
import { join } from 'node:path';
// @boundaries-ignore type-only: the seed-hook contract; @tooling/scripts cannot depend on core (core depends on it for db helpers)
import type { SeedContext } from '../../../packages/core/src/contracts/extensions';
import { writeIfChanged } from './lib/common';
import { buildProducts, type ProductRecord } from './fill-gaps';
import { buildFaqs } from './faqs';
import { buildInputs } from './inputs';
import { buildCms } from './cms-content';
import { normalizePlants } from './normalize-plants';

const rs = (n: number) => `Rs ${n.toLocaleString('en-IN')}`;
const list = (items: string[]) => items.map((s) => `- ${s}`).join('\n');
const names = (ps: ProductRecord[]) => ps.map((p) => p.name_en).join(', ');

export function renderClientQuestions(): string {
  const { products } = buildProducts();
  const client = products.filter((p) => p.data_source === 'client');
  const by = (src: string) => client.filter((p) => p.provenance.price === src);
  const researched = by('researched');
  const native = by('researched_native');
  const sibling = by('woo_sibling');
  const legacy = products.filter((p) => p.data_source === 'woo_legacy');
  const noPhoto = products.filter((p) => p.status === 'active' && p.media.image_needed);
  const replace = client.filter((p) => p.review_notes.some((n) => /replace photo/.test(n)));
  const faqs = buildFaqs();
  const inputs = buildInputs();
  const drafts = buildCms().pages.filter((p) => p.status === 'draft');
  const nativePrices = native.map((p) => p.variants[0]!.price);
  // data-quality notes raised while reading the client file (normalize-plants), not the gap-fill defaults
  const flagLines = normalizePlants()
    .filter((r) => r.review_notes.length)
    .map((r) => `${r.name_en} (sheet row ${r.source_row}): ${r.review_notes.join(' ')}`);

  return `# Client questions

Generated by \`pnpm seed:build\` (tooling/scripts/seed/client-questions.ts) from the seed data; do not edit by hand.
Every item below is live in the store as a sensible default and marked \`needs_review\`; the admin "Data gaps" view lists the same records.

Summary: ${products.length} plant records (${client.length} from the client file, 1 Agarwood, ${legacy.length} old-shop drafts) and ${inputs.length} input products. ${products.filter((p) => p.needs_review).length} records need review.

## 1. Prices

- **${researched.length} researched prices** (no old-shop listing): ${researched.map((p) => `${p.name_en} ${rs(p.variants[0]!.price)}`).join('; ')}.
- **${native.length} native sapling prices** (${rs(Math.min(...nativePrices))} to ${rs(Math.max(...nativePrices))}, from the university nursery rates): confirm the band.
- **${sibling.length} prices borrowed from a sibling listing** (same species, other variety): ${sibling.map((p) => `${p.name_en} ${rs(p.variants[0]!.price)}`).join('; ')}.
- Bulk price = 0.72 x price, from 50 (large), 100 (medium) or 200 (small) plants. Confirm the factor and the thresholds per plant.
- Two price levels for Neem, Soapnut and Sandalwood (bagged tree at the old-shop level vs native Miyawaki seedling): confirm both are wanted.
- Struck-out "compare at" prices are shown only where the old shop had a real regular price.

## 2. Old-shop plants not in the client file (${legacy.length})

Imported as hidden drafts (not for sale, not indexed). Keep as drafts, publish (after adding spacing, climate and compost), or delete?

${names(legacy)}.

## 3. Agarwood

Listed in the Plant list and FAQs but missing from Plant data. It is live with the old-shop price and researched climate. Please add its climate, model spacing, compost and Kannada name.

## 4. Sizes and logistics

- Bag size and dispatch height are defaults by propagation (grafted or air-layered 1.5 to 2 ft in an 8x10 in bag, seedlings 1 to 1.5 ft in a 6x8 in bag). Confirm per plant.
- Weights per sapling with bag are defaults: large 3 kg, medium 2 kg, small 1 kg, native Miyawaki 0.8 kg, slips 0.2 kg. Packing fee Rs 15 / 10 / 5.
- Size variants seeded: Mangosteen (1.5 ft and 6 ft) and N-18 Rambutan (3 ft and 8 ft). Any others?
- Stock: ${client.filter((p) => p.provenance.stock === 'placeholder').length} client plants have no stock figure and show as pre-order (ready in 30 days) until hasiru-ops stock syncs.

## 5. Planting models

- Roles M (main), X (host) and O (biomass) per plant per model are defaults (large = M, medium = X, small or biomass = O). Please send the real roles.
- Model patterns (Commercial M O X O X O M, Food Forest 6 x 6 ft, Miyawaki 2 x 2 ft random mix, Boundary single line) are placeholders.
- Vermicompost and biochar dosages per role are placeholders; please send the real formulas.

## 6. Soil preference

Not in the client file. ${client.filter((p) => p.review_notes.some((n) => /Soil preference/.test(n))).length} plants use a default (well drained, loam, red, laterite). Please send soil preferences per plant.

## 7. FAQ answers

- ${faqs.filter((f) => f.status === 'needs_client').length} questions only the client can answer (permission to grow, yield and earnings, mother plant age, legal and economics questions), for example:
${list(faqs.filter((f) => f.status === 'needs_client' && !f.product_sku).map((f) => f.question)).replace(/^/gm, '  ')}
- ${faqs.filter((f) => f.status === 'draft').length} questions are drafts to be written and approved (host plants, how to plant, maintenance).
- ${faqs.filter((f) => f.status === 'approved').length} answers come straight from the plant data and are published.

## 8. Data fixes in the client file

${list(flagLines)}

## 9. GST and HSN (CA to confirm)

${list(inputs.filter((i) => i.tax.needs_ca_confirmation || i.review_notes.length > 1).map((i) => `${i.name_en}: HSN ${i.tax.hsn}, ${i.tax.gst_rate}% GST. ${i.review_notes.slice(1).join(' ')}`))}
- Input products, pack sizes and prices are samples from the prototype; please send the real list.

## 10. Photos

- ${noPhoto.length} live products have no photo and show a placeholder: ${names(noPhoto)}.
- ${replace.length} products use a photo of a related old listing; replace when real photos exist: ${names(replace)}.
- The old-shop product photos look like stock images of unknown origin; please confirm we may keep using them.

## 11. Content, policies and claims

- Policy pages are drafts with only the SRS wording and stay hidden until you publish them: ${drafts.map((p) => p.title).join(', ')}. Please send the final wording (damage and replacement especially).
- Trust band: "Rated 4.8" stays hidden until you confirm where the rating comes from. The current site says "Incubated at UASB Bio-NEST, Bangalore" while the brief says UAS Dharwad: which is right?
- Counters from the current site (850+ acres, 120+ farms, 200+ varieties) are shown; confirm they are current.
- Cash on delivery is off; payment is online, with an optional part-advance mode. Confirm.

## 12. Delivery and served areas

- Which states do you deliver to (default: Karnataka, Tamil Nadu, Kerala, Andhra Pradesh, Telangana, Goa)? Others get an enquiry instead of checkout.
- District list: add Vijayanagara and the new Andhra Pradesh districts?
`;
}

export default async function step(ctx: SeedContext): Promise<void> {
  // docs/ sits two levels above data/seed in whichever tree the build writes to
  const wrote = writeIfChanged(join(ctx.seedDir, '..', '..', 'docs', 'CLIENT-QUESTIONS.md'), renderClientQuestions(), ctx);
  ctx.log.info(`client-questions: docs/CLIENT-QUESTIONS.md${wrote ? ' written' : ' unchanged'}`);
}
