import type { AppConfig, ModuleManifest, RouteDef } from '../contracts';
import { routeFilePath } from './paths';

export const GENERATED_HEADER = '// generated by modules:sync, do not edit';

export interface GeneratedFile {
  /** App-relative, posix separators. */
  path: string;
  contents: string;
}

const varName = (id: string) => `m_${id.replace(/-/g, '_')}`;

function routeStub(moduleId: string, route: RouteDef): string {
  const lines = [GENERATED_HEADER, `export { ${route.exports.join(', ')} } from '@ecomkit/${moduleId}/${route.module}';`];
  for (const [key, value] of Object.entries(route.segmentConfig ?? {})) {
    lines.push(`export const ${key} = ${JSON.stringify(value)};`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Every file modules:sync owns for one app config, given manifests already in dependency order.
 * Pure: the tooling script does the file IO, `--check` compares, and stale generated files are removed.
 */
export function planFiles(config: AppConfig, ordered: readonly ModuleManifest[]): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const m of ordered) {
    const routes = [...(m.routes ?? []), ...(m.admin?.pages ?? []), ...(config.mocks ? (m.mockRoutes ?? []) : [])];
    for (const route of routes) files.push({ path: routeFilePath(route), contents: routeStub(m.id, route) });
  }

  const ids = ordered.map((m) => m.id);
  files.push({
    path: 'src/generated/registry.ts',
    contents: [
      GENERATED_HEADER,
      `// app: ${config.app}, mocks: ${config.mocks}`,
      `import { createRegistry } from '@ecomkit/core/manifest';`,
      ...ids.map((id) => `import ${varName(id)} from '@ecomkit/${id}/manifest';`),
      '',
      `export const enabledModules = ${JSON.stringify(ids)} as const;`,
      `export const registry = createRegistry([${ids.map(varName).join(', ')}], { mocks: ${config.mocks} });`,
      '',
    ].join('\n'),
  });

  const withSchema = ordered.filter((m) => m.schema);
  files.push({
    path: 'src/generated/schema.ts',
    contents: [
      GENERATED_HEADER,
      ...(withSchema.length ? withSchema.map((m) => `export * from '@ecomkit/${m.id}/schema';`) : ['export {};']),
      '',
    ].join('\n'),
  });

  return files.sort((a, b) => a.path.localeCompare(b.path));
}
